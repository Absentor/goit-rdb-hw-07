"""###Крок 1. Перевіряємо різні способи пошуку в JSONB"""

with engine.connect() as conn:
    # 1. Оператор @> : пошук за вмістом JSON
    containment = pd.read_sql(text("""
        SELECT event_type, payload
        FROM t7_hw_events
        WHERE payload @> '{"device": "mobile"}'::jsonb
        LIMIT 5;
    """), conn)

    # 2. Оператор ? : перевірка наявності ключа
    key_exists = pd.read_sql(text("""
        SELECT event_type, payload
        FROM t7_hw_events
        WHERE payload ? 'payment_method'
        LIMIT 5;
    """), conn)

    # 3. JSONPath : пошук подій, де ціна товару більша за 50
    jsonpath = pd.read_sql(text("""
        SELECT event_type, payload
        FROM t7_hw_events
        WHERE jsonb_path_exists(
            payload,
            '$.price ? (@ > 50)'
        )
        LIMIT 5;
    """), conn)

print("1. Пошук за вмістом (@>):")
display(containment)

print("2. Перевірка наявності ключа (?):")
