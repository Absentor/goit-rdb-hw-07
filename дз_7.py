"""##Завдання 2.2. Rolling 7-day average"""

with engine.connect() as conn:
    rolling_features = pd.read_sql(text("""
        SELECT
            pickup_zone_id,
            ts_day,
            trip_count,

            AVG(trip_count) OVER (
                PARTITION BY pickup_zone_id
                ORDER BY ts_day
                RANGE BETWEEN INTERVAL '6 days' PRECEDING
                          AND CURRENT ROW
            ) AS trips_rolling_7d_avg

        FROM t7_hw_taxi_daily
        ORDER BY pickup_zone_id, ts_day
        LIMIT 20;
    """), conn)

display(rolling_features)

